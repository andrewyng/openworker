export function getLanguage(): Language {
  try {
    return localStorage.getItem(STORAGE_KEY) === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

function interpolate(value: string, vars?: Record<string, string | number>): string {
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translate(language: Language, key: string, vars?: Record<string, string | number>): string {
  const value = messages[language][key] ?? messages.en[key] ?? key;
  return interpolate(value, vars);
}

export function setLanguage(language: Language): void {
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Private browsing or a restricted webview can still switch for this session.
  }
  window.dispatchEvent(new CustomEvent(LANGUAGE_EVENT));
}

interface I18nContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const defaultI18nContext: I18nContextValue = {
  language: "en",
  setLanguage,
  t: (key, vars) => translate("en", key, vars),
};

const I18nContext = createContext<I18nContextValue>(defaultI18nContext);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setCurrentLanguage] = useState<Language>(getLanguage);
  useEffect(() => {
    const sync = () => setCurrentLanguage(getLanguage());
    window.addEventListener(LANGUAGE_EVENT, sync);
    return () => window.removeEventListener(LANGUAGE_EVENT, sync);
  }, []);
  const changeLanguage = useCallback((next: Language) => {
    setCurrentLanguage(next);
    setLanguage(next);
  }, []);
  const value = useMemo(
    () => ({ language, setLanguage: changeLanguage, t: (key: string, vars?: Record<string, string | number>) => translate(language, key, vars) }),
    [changeLanguage, language],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
